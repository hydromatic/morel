package net.hydromatic.morel.eval;

import static java.util.Objects.requireNonNull;

import com.google.common.base.Suppliers;
import com.google.common.collect.ImmutableMap;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;
import java.util.function.Consumer;
import java.util.function.Supplier;
import net.hydromatic.morel.ast.Core;
import net.hydromatic.morel.ast.Pos;
import net.hydromatic.morel.compile.BagPrinter;
import net.hydromatic.morel.compile.CompileException;
import net.hydromatic.morel.compile.Environment;
import net.hydromatic.morel.compile.NameGenerator;
import net.hydromatic.morel.type.TypeSystem;
import net.hydromatic.morel.util.ColorScheme;
import net.hydromatic.morel.util.MorelException;
import org.jspecify.annotations.Nullable;

/**
 * Session environment.
 *
 * <p>Accessible from {@link EvalEnv#getOpt(String)} via the hidden "$session"
 * variable.
 */
public class Session {
  /**
   * A dummy session for use in compile-time constant evaluation (e.g. inlining,
   * constant-folding). It has an empty {@link #globalEnv}, no type system, and
   * throws {@link UnsupportedOperationException} for any shell-level operations
   * ({@code use}, {@code clearEnv}).
   */
  public static final Session EMPTY = createEmpty();

  private static Session createEmpty() {
    final Session s = new Session(ImmutableMap.of());
    s.globalEnv = ImmutableMap.of();
    return s;
  }

  /**
   * The authoritative global environment, as a flat name-to-value map.
   *
   * <p>Updated after each top-level statement so that closures created during
   * that statement always see the latest bindings when invoked later, without
   * per-closure patching.
   *
   * <p>Group/aggregate and CalciteCompiler bridge code temporarily mutate this
   * map (put + restore) during evaluation.
   */
  public Map<String, Object> globalEnv = ImmutableMap.of();

  /** The plan of the previous command. */
  public @Nullable Code code;
  /** The output lines of the previous command. */
  public @Nullable List<String> out;
  /** The AST of the previous command, for re-planning. */
  public Core.@Nullable Decl coreDecl;
  /** The compile environment of the previous command, for re-planning. */
  public @Nullable Environment environment;
  /** Property values. */
  public final Map<Prop, Object> map;

  /**
   * File system.
   *
   * <p>Wrapped in a Supplier to avoid the cost of initializing it (scanning a
   * directory) for every session.
   */
  public final Supplier<File> file;

  /**
   * Type system for this session.
   *
   * <p>Used by variant constructors to create properly-typed instances of
   * {@link Variant}.
   */
  public final @Nullable TypeSystem typeSystem;

  /**
   * Name generator. Ensures that internal names generated by various statements
   * in this session do not overlap.
   */
  public final NameGenerator nameGenerator = new NameGenerator();

  /** Controls element ordering when printing bag values. */
  private BagPrinter bagPrinter = BagPrinter.NATURAL;

  /** Implementation of "use". */
  private Shell shell = Shells.INSTANCE;

  /**
   * Creates a Session.
   *
   * <p>The {@code map} parameter, that becomes the property map, is used as is,
   * not copied. It may be immutable if the session is for a narrow, internal
   * use. Otherwise, it should probably be a {@link LinkedHashMap} to provide
   * deterministic iteration order.
   *
   * @param map Map that contains property values
   */
  public Session(Map<Prop, Object> map) {
    this(map, null);
  }

  /**
   * Creates a Session with a TypeSystem.
   *
   * @param map Map that contains property values
   * @param typeSystem Type system for this session (may be null for internal
   *     use)
   */
  public Session(Map<Prop, Object> map, @Nullable TypeSystem typeSystem) {
    this.map = map;
    this.typeSystem = typeSystem;
    this.file =
        Suppliers.memoize(
            () -> Files.create(Prop.DIRECTORY.fileValue(this.map)));
  }

  /**
   * Returns the color scheme in effect for syntax highlighting: the {@link
   * Prop#COLOR_SCHEME} property if it names a built-in scheme, otherwise the
   * scheme deduced from the terminal's background (the {@link
   * Prop#TERMINAL_BACKGROUND} property). Shared by the shell's highlighter and
   * {@code Sys.deduceColorScheme}.
   */
  public ColorScheme colorScheme() {
    return ColorScheme.resolve(
        (String) Prop.COLOR_SCHEME.get(map),
        (String) Prop.TERMINAL_BACKGROUND.get(map));
  }

  /** Calls some code with a new value of {@link Shell}. */
  public void withShell(
      Shell shell, Consumer<String> outLines, Consumer<Session> consumer) {
    final Shell prevShell = this.shell;
    try {
      this.shell = requireNonNull(shell, "shell");
      consumer.accept(this);
    } catch (RuntimeException e) {
      final StringBuilder buf = new StringBuilder();
      prevShell.handle(e, buf);
      outLines.accept(buf.toString());
    } finally {
      this.shell = prevShell;
    }
  }

  /** Calls some code with a {@link Shell} that does not handle errors. */
  public void withoutHandlingExceptions(Consumer<Session> consumer) {
    final Shell prevShell = this.shell;
    try {
      this.shell = Shells.BARF;
      consumer.accept(this);
    } finally {
      this.shell = prevShell;
    }
  }

  public void use(String fileName, boolean silent, Pos pos) {
    shell.use(fileName, silent, pos);
  }

  public void handle(MorelException e, StringBuilder buf) {
    shell.handle((RuntimeException) e, buf);
  }

  public void clearEnv() {
    shell.clearEnv();
  }

  /** Returns the current BagPrinter. */
  public BagPrinter bagPrinter() {
    return bagPrinter;
  }

  /** Sets the BagPrinter. */
  public void setBagPrinter(BagPrinter bagPrinter) {
    this.bagPrinter = requireNonNull(bagPrinter);
  }

  /** Callback to implement "use" command. */
  public interface Shell {
    void use(String fileName, boolean silent, Pos pos);

    /**
     * Handles an exception. Particular implementations may re-throw the
     * exception, or may format the exception to a buffer that will be added to
     * the output. Typically, a root shell will handle the exception, and
     * sub-shells will re-throw.
     */
    void handle(RuntimeException e, StringBuilder buf);

    /** Clears the environment. Default implementation does nothing. */
    default void clearEnv() {}
  }

  /** Various implementations of {@link Shell}. */
  private enum Shells implements Shell {
    /** Default instance of Shell. */
    INSTANCE {
      @Override
      public void handle(RuntimeException e, StringBuilder buf) {
        if (e instanceof Codes.MorelRuntimeException) {
          ((Codes.MorelRuntimeException) e).describeTo(buf);
        } else if (e instanceof CompileException) {
          buf.append(e.getMessage());
        } else {
          buf.append(e);
        }
      }
    },

    /** Instance of Shell that does not handle exceptions. */
    BARF {
      @Override
      public void handle(RuntimeException e, StringBuilder buf) {
        throw e;
      }
    };

    @Override
    public void use(String fileName, boolean silent, Pos pos) {
      throw new UnsupportedOperationException();
    }
  }
}

